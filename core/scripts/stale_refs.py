# -*- coding: utf-8 -*-
"""Stale-reference audit: which backticked script, file or folder names in the key notes no longer exist?

Documentation drifts: a script is renamed, a note is moved, and the boot file or the index keeps naming the old one.
This reads the notes you give it (read-only, nothing is changed) and checks every `name.py`, `folder/note.md` or `folder/`
written in single backticks against the assistant folder: its scripts, .claude, logs, vault and the vault's top folders.

    python stale_refs.py [note ...]     # default: the boot file (CLAUDE.md), the vault index, Active Priorities, How This Assistant Works
    python stale_refs.py --json         # the same result as JSON
    python stale_refs.py --job          # scheduler form: tells notify.py once, always exits 0, honours logs/stale_refs_off.txt

What counts (a name that is not found is put in exactly one bucket):
    missing   a script, note or folder that is named but does not exist: likely stale, renamed, or never built. These make the exit code 1.
    runtime   a state file (anything under logs/, or .jsonl/.log/.txt/.csv) that does not exist YET; scripts create them when they first run. Listed, not counted.
    planned   named on a line that says it is created/written/generated by something, or is produced weekly/daily/nightly: expected to be absent until then. Listed, not counted.
    unchecked a name with a `..` segment is never looked up. Listed in the summary count only.
Command lines are understood: for `python scripts/x.py --flag` the script `scripts/x.py` is the reference.

Paths: ROOT is the parent of the scripts folder (HARNESS_ROOT overrides), the notes folder is ROOT/vault (HARNESS_VAULT), logs are ROOT/logs
(HARNESS_LOGS). Exit codes: 0 clean, 1 something missing, 2 no note could be read."""
import argparse
import json
import os
import re
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
NAME = "stale_refs"
MAX_NOTE_BYTES = 2_000_000
MAX_FILES_INDEXED = 30000
MAX_LISTED = 40

EXTS = ("py", "ps1", "bat", "cmd", "sh", "vbs", "json", "jsonl", "md", "txt", "csv", "yml", "yaml", "toml", "log")
SCRIPT_EXTS = ("py", "ps1", "bat", "cmd", "sh", "vbs")
RUNTIME_EXTS = {"jsonl", "log", "txt", "csv"}
HAS_EXT = re.compile(r"\.(?:%s)$" % "|".join(EXTS), re.I)
HAS_SCRIPT_EXT = re.compile(r"\.(?:%s)$" % "|".join(SCRIPT_EXTS), re.I)
SPAN = re.compile(r"(?<!`)`([^`\n]+)`(?!`)")
FILE_CHARS = re.compile(r"[\w\-./\\: ()~]+")
DIR_CHARS = re.compile(r"[\w\-./\\ ()~]+")
FENCE = re.compile(r"^[ \t>]*(`{3,}|~{3,})(.*)$")
INTERPRETER = re.compile(r"^(?:python3?|pythonw|py|node|bash|sh|pwsh|powershell)(?:\.exe)?\s+", re.I)
BAD_CHARS = re.compile(r"[<>*?{}$|\"']")
PLANNED = re.compile(r"\b(created|written|generated|produced|appears?|will be|planned|not built yet|todo|weekly|daily|nightly|hourly)\b", re.I)


def root():
    return Path(os.environ.get("HARNESS_ROOT") or HERE.parent).resolve()


def vault():
    return Path(os.environ.get("HARNESS_VAULT") or root() / "vault").resolve()


def logs():
    return Path(os.environ.get("HARNESS_LOGS") or root() / "logs").resolve()


ROOT = root()
LOGS = logs()
VAULT = vault()


# ---------- reading tokens out of a note ----------
def _lines_outside_fences(text):
    """(line number, line) for every line that is not inside a ``` or ~~~ fenced block. An unclosed fence hides the rest, as a viewer would."""
    fence = None
    for n, line in enumerate((text or "").splitlines(), 1):
        m = FENCE.match(line)
        if fence is None:
            if m and not (m.group(1)[0] == "`" and "`" in m.group(2)):
                fence = m.group(1)
                continue
            yield n, line
        elif m and m.group(1)[0] == fence[0] and len(m.group(1)) >= len(fence) and not m.group(2).strip():
            fence = None


def _clean(tok):
    """False for placeholders, globs, URLs and anything that is not a plain name."""
    return (bool(tok) and len(tok) <= 200 and not BAD_CHARS.search(tok) and "..." not in tok and "YYYY" not in tok
            and "://" not in tok and tok.strip(". /\\") != "")


def candidate(span):
    """-> (token, kind) for a backticked span that names a file ('file') or a folder ('dir'), else None. Pure.
    A span that starts with an interpreter names its first word; a span with a script first word and arguments names that script."""
    s = span.strip()
    if not s:
        return None
    m = INTERPRETER.match(s)
    if m:
        rest = s[m.end():].strip()
        first = rest.split(None, 1)[0].strip("\"'") if rest else ""
        if HAS_EXT.search(first) and _clean(first):
            return first, "file"
        return None
    if HAS_EXT.search(s) and FILE_CHARS.fullmatch(s) and _clean(s):
        return s, "file"
    if (s.endswith("/") or s.endswith("\\")) and len(s) > 1 and DIR_CHARS.fullmatch(s) and _clean(s) and not HAS_EXT.search(s.rstrip("/\\")):
        return s, "dir"
    parts = s.split(None, 1)
    if len(parts) == 2 and HAS_SCRIPT_EXT.search(parts[0]) and _clean(parts[0]):
        return parts[0], "file"
    return None


def extract(text):
    """-> [(token, kind, planned)] in order of first appearance. `planned` is true only when every line that names the token says it is created/written by something."""
    seen, order = {}, []
    for _n, line in _lines_outside_fences(text):
        planned = bool(PLANNED.search(line))
        for m in SPAN.finditer(line):
            got = candidate(m.group(1))
            if not got:
                continue
            tok, kind = got
            key = (tok, kind)
            if key not in seen:
                seen[key] = planned
                order.append(key)
            else:
                seen[key] = seen[key] and planned
    return [(t, k, seen[(t, k)]) for t, k in order]


# ---------- looking names up ----------
def _is_abs(tok):
    return bool(re.match(r"^[A-Za-z]:[\\/]", tok)) or tok.startswith(("/", "\\\\", "~"))


def _norm_rel(tok):
    """A relative token with forward slashes and no leading ./ (a leading dot of a hidden folder such as .claude is kept)."""
    rel = tok.strip().replace("\\", "/")
    while rel.startswith("./"):
        rel = rel[2:]
    return rel


class Resolver:
    """Knows where names may live. Built once per run so a long note list does not walk the disk again and again."""

    def __init__(self, root_dir=None, vault_dir=None, logs_dir=None):
        self.root = Path(root_dir) if root_dir else root()
        self.vault = Path(vault_dir) if vault_dir else vault()
        self.logs = Path(logs_dir) if logs_dir else logs()
        self.bases = [self.root, self.root / "scripts", self.root / ".claude", self.root / ".claude" / "skills",
                      self.root / ".claude" / "agents", self.logs, self.vault]
        try:
            self.bases += sorted(p for p in self.vault.iterdir() if p.is_dir() and not p.name.startswith("."))
        except OSError:
            pass
        self.aliases = {"vault": self.vault, "logs": self.logs}
        self.names = set()
        self._index_names()

    def _index_names(self):
        count = 0
        for top in (self.root / "scripts", self.root / ".claude", self.vault, self.logs):
            for d, dirs, files in os.walk(top):
                dirs[:] = [x for x in dirs if not x.startswith(".")]
                for f in files:
                    self.names.add(f)
                    count += 1
                if count >= MAX_FILES_INDEXED:
                    return
        try:
            self.names.update(p.name for p in self.root.iterdir() if p.is_file())
        except OSError:
            pass

    def _candidates(self, rel):
        out = []
        head, _, tail = rel.partition("/")
        if head in self.aliases and tail:
            out.append(self.aliases[head] / tail)
        out += [b / rel for b in self.bases]
        return out

    def exists(self, tok, kind="file"):
        t = tok.strip()
        try:
            if _is_abs(t):
                p = Path(os.path.expanduser(t))
                return p.is_dir() if kind == "dir" else p.exists()
            rel = _norm_rel(t)
            rel = rel.rstrip("/") if kind == "dir" else rel
            if kind == "file" and "/" not in rel and rel in self.names:
                return True
            for p in self._candidates(rel):
                if (p.is_dir() if kind == "dir" else p.exists()):
                    return True
        except (OSError, ValueError):
            return False
        return False


def _is_runtime(tok):
    rel = _norm_rel(tok)
    ext = rel.rsplit(".", 1)[-1].lower() if "." in rel.rsplit("/", 1)[-1] else ""
    return rel.startswith("logs/") or rel == "logs" or ext in RUNTIME_EXTS


def audit_text(text, resolver):
    """-> {referenced, missing, runtime, planned, unchecked}: lists of tokens. Pure apart from looking names up."""
    out = {"referenced": [], "missing": [], "runtime": [], "planned": [], "unchecked": []}
    for tok, kind, planned in extract(text):
        out["referenced"].append(tok)
        if ".." in tok.replace("\\", "/").split("/"):
            out["unchecked"].append(tok)
            continue
        if resolver.exists(tok, kind):
            continue
        if planned:
            out["planned"].append(tok)
        elif _is_runtime(tok):
            out["runtime"].append(tok)
        else:
            out["missing"].append(tok)
    return out


def read_note(path):
    """The note's text (at most MAX_NOTE_BYTES), or None when it cannot be read."""
    try:
        with open(path, "rb") as f:
            return f.read(MAX_NOTE_BYTES).decode("utf-8", errors="replace")
    except OSError:
        return None


def audit_note(path, resolver):
    """-> audit_text result for one file, or None when the file cannot be read."""
    text = read_note(path)
    return None if text is None else audit_text(text, resolver)


def default_notes():
    v = vault()
    cands = [root() / "CLAUDE.md", v / "VAULT-INDEX.md", v / "Active Priorities.md", v / "05 - Resources" / "How This Assistant Works.md"]
    return [p for p in cands if p.is_file()]


# ---------- reporting ----------
def _notify(text):
    try:
        if str(HERE) not in sys.path:
            sys.path.insert(0, str(HERE))
        import notify
        notify.alert(text, source=NAME, intent_kind="stale_reference", tier=1, value=2, dedupe="stale-refs", logs=logs())
    except Exception:
        try:
            lg = logs()
            lg.mkdir(parents=True, exist_ok=True)
            with open(lg / "alerts.txt", "a", encoding="utf-8") as f:
                f.write("[%s] %s: %s\n" % (time.strftime("%Y-%m-%d %H:%M:%S"), NAME, " ".join(text.split())[:500]))
        except OSError:
            pass


def run(notes, resolver=None):
    """-> list of {note, path, result|None}. A note that cannot be read has result None."""
    resolver = resolver or Resolver()
    return [{"note": Path(n).name, "path": str(n), "result": audit_note(n, resolver)} for n in notes]


def main(argv=None):
    ap = argparse.ArgumentParser(description="List backticked file and folder names in notes that no longer exist.")
    ap.add_argument("notes", nargs="*", help="notes to check (default: boot file, vault index, Active Priorities, How This Assistant Works)")
    ap.add_argument("--json", action="store_true", help="print the result as JSON")
    ap.add_argument("--job", action="store_true", help="scheduler form: notify once, always exit 0")
    args = ap.parse_args(argv)
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass
    if args.job and (logs() / (NAME + "_off.txt")).exists():
        print("%s: off (logs/%s_off.txt exists)" % (NAME, NAME))
        return 0
    notes = args.notes or default_notes()
    if not notes:
        print("no notes found to check (looked for CLAUDE.md and the vault index under %s)" % root())
        return 0 if args.job else 2
    rows = run(notes)
    unreadable = [r for r in rows if r["result"] is None]
    total = sum(len(r["result"]["missing"]) for r in rows if r["result"])
    if args.json:
        print(json.dumps({"notes": rows, "missing_total": total}, ensure_ascii=False, indent=1))
    else:
        for r in rows:
            res = r["result"]
            if res is None:
                print("missing note: %s" % r["path"])
                continue
            extra = ", ".join("%d %s" % (len(res[k]), label) for k, label in (("runtime", "state files not created yet"), ("planned", "planned"), ("unchecked", "unchecked")) if res[k])
            print("%s: %d referenced, %d not found%s" % (r["note"], len(res["referenced"]), len(res["missing"]), " (" + extra + ")" if extra else ""))
            for t in res["missing"][:MAX_LISTED]:
                print("    " + t)
            if len(res["missing"]) > MAX_LISTED:
                print("    ... and %d more" % (len(res["missing"]) - MAX_LISTED))
    if args.job:
        if total:
            first = next((r for r in rows if r["result"] and r["result"]["missing"]), None)
            _notify("%d stale reference(s) in key notes, e.g. %s in %s. Run: python scripts/stale_refs.py" % (total, first["result"]["missing"][0], first["note"]))
        return 0
    if len(unreadable) == len(rows):
        return 2
    return 1 if (total or unreadable) else 0


if __name__ == "__main__":
    sys.exit(main())
